package main

import (
	"bytes"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

// tree builds a source tree with one rule template and gen.yaml enabling rules.
func tree(t *testing.T, rulesYAML string) string {
	t.Helper()
	root := t.TempDir()
	files := map[string]string{
		".claude/src/gen.yaml":        "targets: [rules]\n",
		".claude/src/rules/a.md.tmpl": "## A\n",
		".claude/src/rules.yaml":      rulesYAML,
	}
	for rel, content := range files {
		p := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return root
}

// runCLI runs the CLI with args and returns its exit status and stderr.
func runCLI(args ...string) (int, string) {
	var out, errOut bytes.Buffer
	code := run(args, &out, &errOut)
	return code, errOut.String()
}

// just lint runs --check right after a regenerate; they must agree.
func TestRunWritesThenCheckClean(t *testing.T) {
	root := tree(t, "[]\n")
	if code, errOut := runCLI("--root", root); code != 0 {
		t.Fatalf("write exit %d: %s", code, errOut)
	}
	if _, err := os.Stat(filepath.Join(root, ".claude/rules/a.md")); err != nil {
		t.Fatal(err)
	}
	if code, errOut := runCLI("--root", root, "--check"); code != 0 {
		t.Fatalf("check exit %d: %s", code, errOut)
	}
}

// This is the gate that stops hand-edited generated files from landing.
func TestRunCheckExits1OnDrift(t *testing.T) {
	root := tree(t, "[]\n")
	runCLI("--root", root)
	if err := os.WriteFile(filepath.Join(root, ".claude/rules/a.md"), []byte("edited\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	code, errOut := runCLI("--root", root, "--check")
	if code != 1 || !strings.Contains(errOut, ".claude/rules/a.md") {
		t.Fatalf("exit %d, stderr %q", code, errOut)
	}
}

// A half-applied render from a broken model leaves the config inconsistent.
func TestRunInvalidModelWritesNothing(t *testing.T) {
	root := tree(t, "- {id: a, statement: s, severity: fatal, enforce: prose, targets: [x]}\n")
	code, errOut := runCLI("--root", root)
	if code != 1 || !strings.Contains(errOut, "rules.yaml:/0/severity") {
		t.Fatalf("exit %d, stderr %q", code, errOut)
	}
	if _, err := os.Stat(filepath.Join(root, ".claude/rules/a.md")); err == nil {
		t.Fatal("a.md was written despite an invalid model")
	}
}

// Scripts distinguish a usage mistake (2) from drift (1).
func TestRunBadFlagExits2(t *testing.T) {
	if code, _ := runCLI("--nope"); code != 2 {
		t.Fatalf("exit %d, want 2", code)
	}
}

// A target that renders one file (CLAUDE.md) must not treat every generated file in that file's directory as its orphan; that once deleted the generator's own golden fixtures.
func TestRunLeavesMarkedFilesOutsideOwnedDirs(t *testing.T) {
	root := tree(t, "[]\n")
	extra := map[string]string{
		".claude/src/gen.yaml":       "targets: [rules, claude-md]\n",
		".claude/src/claude.md.tmpl": "# Standards\n",
		".claude/gen/testdata/x.md":  "<!-- Code generated by claude-gen; DO NOT EDIT. -->\nfixture\n",
	}
	for rel, content := range extra {
		p := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	if code, errOut := runCLI("--root", root); code != 0 {
		t.Fatalf("exit %d: %s", code, errOut)
	}
	if _, err := os.Stat(filepath.Join(root, ".claude/gen/testdata/x.md")); err != nil {
		t.Fatalf("marked fixture outside owned dirs was deleted: %v", err)
	}
}

// A wrong --root (no .claude/src) used to report "no drift" and exit 0, so a misconfigured just lint passed while checking nothing.
func TestRunCheckFailsWithNoTargets(t *testing.T) {
	code, errOut := runCLI("--root", t.TempDir(), "--check")
	if code != 2 {
		t.Fatalf("exit %d, want 2: %s", code, errOut)
	}
	if !strings.Contains(errOut, "gen.yaml") || !strings.Contains(errOut, "targets") {
		t.Fatalf("stderr does not name the missing targets: %q", errOut)
	}
}

// Deleting a target's last template must surface its stale outputs as orphans, not be mistaken for "no targets enabled".
func TestRunCheckReportsOrphanWhenTargetRendersNothing(t *testing.T) {
	root := tree(t, "[]\n")
	if code, errOut := runCLI("--root", root); code != 0 {
		t.Fatalf("write exit %d: %s", code, errOut)
	}
	if err := os.Remove(filepath.Join(root, ".claude/src/rules/a.md.tmpl")); err != nil {
		t.Fatal(err)
	}
	code, errOut := runCLI("--root", root, "--check")
	if code != 1 || !strings.Contains(errOut, "orphan .claude/rules/a.md") {
		t.Fatalf("exit %d: %q", code, errOut)
	}
}
