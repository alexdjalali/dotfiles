// Skill frontmatter decides model, effort, context and invocation; a rendering slip changes how every skill runs.
func TestSkillsGolden(t *testing.T) {
	files := renderLoaded(t, "skills", "../testdata/skills")
	if len(files) != 2 {
		t.Fatalf("rendered %d files, want 2", len(files))
	}
	for _, f := range files {
		name := filepath.Base(filepath.Dir(f.Path))
		want, err := os.ReadFile(filepath.Join("../testdata/skills/golden", name, "SKILL.md"))
		if err != nil {
			t.Fatal(err)
		}
		if f.Path != ".claude/skills/"+name+"/SKILL.md" || string(f.Data) != string(want) {
			t.Errorf("%s:\n got:\n%s\nwant:\n%s", f.Path, f.Data, want)
		}
	}
}

// Claude Code runs a !`cmd` line before the skill loads; anything else reaches the model as literal text.
func TestInjectRendersBangLines(t *testing.T) {
	files := renderLoaded(t, "skills", "../testdata/skills")
	body := string(files[0].Data)
	if !strings.Contains(body, "---\n\n!`git status --short`\n!`git diff --stat HEAD`\n\n") {
		t.Fatalf("body = %q", body)
	}
}

// Frontmatter must start on line 1 and keep a stable key order, so regenerating never churns every file.
func TestFrontmatterKeyOrder(t *testing.T) {
	files := renderLoaded(t, "skills", "../testdata/skills")
	lines := strings.Split(string(files[1].Data), "\n")
	want := []string{"---", "# Code generated by claude-gen; DO NOT EDIT.", "name: beta", "model: sonnet", "effort: medium"}
	for i, w := range want {
		if lines[i] != w {
			t.Fatalf("line %d = %q, want %q", i, lines[i], w)
		}
	}
}

// An argument hint of null or 123 written plain re-parses as YAML null or a number, so Claude Code would read a different value than the source.
func TestFrontmatterKeepsStringsStrings(t *testing.T) {
	root := t.TempDir()
	for rel, content := range map[string]string{
		".claude/src/skills/gamma.yaml":    "name: gamma\ndescription: \"123\"\nargument_hint: \"null\"\n",
		".claude/src/skills/gamma.md.tmpl": "Body.\n",
	} {
		p := filepath.Join(root, rel)
		if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
			t.Fatal(err)
		}
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	files := renderLoaded(t, "skills", root)
	parts := strings.SplitN(string(files[0].Data), "---\n", 3)
	var fm map[string]any
	if err := yaml.Unmarshal([]byte(parts[1]), &fm); err != nil {
		t.Fatal(err)
	}
	if fm["description"] != "123" || fm["argument-hint"] != "null" {
		t.Fatalf("frontmatter = %#v", fm)
	}
}
