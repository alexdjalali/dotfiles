#!/usr/bin/env bash
# guard-bash.sh
#
# Claude Code PreToolUse hook for the Bash tool. Sessions run in auto mode
# (permissions.defaultMode "auto") with an empty deny list, so the only other
# check is a model classifier; this is the deterministic backstop against
# destructive commands. A command it catches is not refused: it goes to the
# user's permission prompt with the reason (hook_lib.sh), and the user's
# approval is the override.
# It catches:
#   - force-pushes (or deletes) of main/master (`heads/main` too), a wildcard
#     destination or every matching branch (`:`), including a bare
#     `git push -f` while main is checked out or when the checked-out branch
#     cannot be determined; any `git push --mirror`; a forced --all or
#     --branches (abbreviations included)
#   - recursive rm of /, ~, $HOME, or an ancestor of $HOME, including relative
#     targets such as `*` run from the home directory, also behind a wrapper
#     the parser does not know (`mise exec -- rm -rf *`); git's own `rm`
#     subcommand is not an rm
#   - git reset --hard, git checkout of paths (or -f), git switch
#     --discard-changes / -f, git restore of the working tree, git clean -f
#   - the catalog rows in guard_rules.json, generated by claude-gen from the
#     rule catalog (.claude/src/rules.yaml) and read by guard_rows.py; a
#     missing or corrupt table asks about every command:
#       - git hook bypasses: `--no-verify` on commit/push/merge/rebase/am,
#         `-n` on commit, LEFTHOOK=0/false (inline, through sudo/env, or
#         `export` / `declare -x`), and core.hooksPath overrides (`-c`,
#         `--config-env`, GIT_CONFIG_KEY_<n>, `git config` set/unset)
#       - live infrastructure changes: terraform/tofu/terragrunt apply,
#         destroy, import, state edits; kubectl delete/apply/patch/scale/…;
#         helm install/upgrade/uninstall/rollback; mutating aws/gcloud/az
#         calls (rule infra-needs-user lists them all)
# Long options match git's unambiguous abbreviations (`--har`, `--no-veri`).
# git, or a catalog command-row program, behind a wrapper the parser does not
# know (`mise exec -- git …`, `aws-vault exec p -- terraform apply`) is judged
# as if run directly. An unquoted mention (`echo git push -f origin main`) is
# judged the same way.
#
# Scope: this catches *accidental* destructive commands, the ones a model or a
# tired human actually types. It is not a sandbox against deliberate evasion.
# Known unhandled spellings: a banned value exported in two steps
# (`LEFTHOOK=0; export LEFTHOOK`), core.hooksPath set through exported
# GIT_CONFIG_* or GIT_CONFIG_PARAMETERS, character-class or brace globs
# (`rm -rf ~/[a-z]*`, `~/{*,.*}`), home paths spelled through `..` or odd
# casing beyond simple case folding, `env -S` with its string attached
# (`-S'…'`, `--split-string=…`), an escaped backslash before a line break
# (`\\` + newline), a `$(...)` inside double quotes after a `cd` in the same
# command (checked against the starting directory), a heredoc fed to a
# quoted shell name (`"$SHELL" <<EOF`, `ssh host 'bash -s' <<EOF`), a
# command passed to `su -c` (not evaluated like `bash -c`), rm run as a user
# named git through a wrapper the parser does not know, or with a dash-option
# between the git word and rm (`gosu git rm -rf /`, `runuser -u git -- rm …`,
# `ssh -l git -C host rm …` read as `git rm`), `git rm -f` without
# `--cached`, which drops uncommitted edits to the files it removes (git's rm
# is exempt from the rm check and has no rule of its own), and infrastructure
# changed through an API rather than its CLI (an SDK script, an MCP tool).
#
# The structural rules and the shell-aware parsing live in guard_bash.py (the
# table rows in guard_rows.py), run by the first python3 on PATH (3.9 or
# newer). This launcher exists so the hook fails toward the prompt: when the
# evaluator cannot run (python3 missing, a broken pyenv shim, a too-old
# interpreter, a crash) the command is asked about rather than let through.
# The hook entry in settings.json sets `onFailure: "block"` (a refusal) for
# the cases it cannot ask about: this file missing, a crash, or a timeout.
# The directory comes from parameter expansion, not dirname: with no PATH
# hook_lib.sh would never load and every hook_ask would fail open. A failed
# source refuses (exit 2), since nothing can ask without hook_lib.sh.
here=${BASH_SOURCE[0]%/*}
[[ $here == "${BASH_SOURCE[0]}" ]] && here=.
# shellcheck source=hook_lib.sh
source "$here/hook_lib.sh" || exit 2

command -v python3 >/dev/null 2>&1 || hook_ask guard-bash "needs python3 to inspect commands, so the command was not checked"
out=$(python3 "$here/guard_bash.py")
status=$?
[[ $status -eq 0 ]] || hook_ask guard-bash "the command guard failed (exit $status), so the command was not checked"
[[ -z $out ]] || printf '%s\n' "$out"
exit 0
